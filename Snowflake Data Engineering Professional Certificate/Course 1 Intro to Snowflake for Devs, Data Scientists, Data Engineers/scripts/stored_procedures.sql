SET max_ts = (SELECT MAX(ORDER_TS) FROM FROSTBYTE_TASTY_BYTES_CLONE.RAW_POS.ORDER_HEADER);
SELECT $max_ts;
SELECT DATEADD('DAY',-180,$max_ts);
SET cutoff_ts = (SELECT DATEADD('DAY',-180,$max_ts));

SELECT MAX(ORDER_TS) FROM FROSTBYTE_TASTY_BYTES_CLONE.RAW_POS.ORDER_HEADER WHERE ORDER_TS < $cutoff_ts;

USE DATABASE frostbyte_tasty_bytes;

CREATE OR REPLACE PROCEDURE delete_old()
RETURNS BOOLEAN 
LANGUAGE SQL
AS
$$
DECLARE 
    max_ts TIMESTAMP;
    cutoff_ts TIMESTAMP;
BEGIN
    max_ts := (SELECT MAX(ORDER_TS) FROM FROSTBYTE_TASTY_BYTES_CLONE.RAW_POS.ORDER_HEADER);
    cutoff_ts := (SELECT DATEADD('DAY',-180,:max_ts));
    DELETE FROM FROSTBYTE_TASTY_BYTES_CLONE.RAW_POS.ORDER_HEADER
    WHERE ORDER_TS < :cutoff_ts;
END;
$$

SHOW PROCEDURES;
DESCRIBE PROCEDURE delete_old();
CALL DELETE_OLD();

