CREATE DATABASE IF NOT EXISTS tasty_bytes_clone CLONE tasty_bytes;

CREATE OR REPLACE PROCEDURE increase_prices()
RETURNS BOOLEAN
LANGUAGE SQL
AS
$$
BEGIN
    UPDATE tasty_bytes_clone.raw_pos.menu SET SALE_PRICE_USD = menu.SALE_PRICE_USD + 1;
END;
$$;

CALL increase_prices();

DESCRIBE PROCEDURE increase_prices();

CREATE OR REPLACE PROCEDURE FROSTBYTE_TASTY_BYTES.PUBLIC.decrease_mango_sticky_rice_price()
RETURNS BOOLEAN
LANGUAGE SQL
AS
$$
BEGIN
    UPDATE tasty_bytes_clone.raw_pos.menu
    SET SALE_PRICE_USD = SALE_PRICE_USD - 1
    WHERE MENU_ITEM_NAME = 'Mango Sticky Rice';
END;
$$;

CALL decrease_mango_sticky_rice_price();